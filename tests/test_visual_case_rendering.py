# ─── Visual regression with PNG baselines (BLOCKER 7) ────────────────────

class TestVisualRegression:
    """Visual regression baseline comparison using PNG reference images.

    Baselines are stored as compressed PNGs under
    tests/fixtures/baselines/case-<name>.png.

    IMPORTANT: Baselines are NEVER auto-generated by this test.
    To regenerate baselines, run:

        python scripts/regenerate_case_baselines.py

    This is an explicit developer action to prevent CI from silently
    blessing a changed renderer.
    """

    def test_visual_baseline_match(self, template):
        """Rendered output should match saved baseline within tolerance."""
        for name, filename, fit_mode in ARTWORKS:
            baseline_path = os.path.join(BASELINE_DIR, f"case-{name}.png")

            if not os.path.exists(baseline_path):
                pytest.fail(
                    f"Baseline not found: {baseline_path}. "
                    f"Run 'python scripts/regenerate_case_baselines.py' "
                    f"to generate baselines."
                )

            # Render
            art_path = os.path.join(FIXTURES_DIR, filename)
            art = Image.open(art_path).convert("RGBA")
            result = render_case(art, template, template_dir=TEMPLATE_DIR, fit_mode=fit_mode)
            result_arr = np.array(result).astype(np.int16)

            # Load baseline
            baseline = Image.open(baseline_path).convert("RGBA")
            baseline_arr = np.array(baseline).astype(np.int16)

            assert baseline_arr.shape == result_arr.shape, \
                f"{name}: shape mismatch {result_arr.shape} vs {baseline_arr.shape}"

            # Mean absolute difference across all channels
            diff = np.abs(result_arr - baseline_arr)
            mean_diff = diff.mean()

            assert mean_diff <= VISUAL_TOLERANCE, \
                (f"{name}: visual diff {mean_diff:.2f} exceeds tolerance "
                 f"{VISUAL_TOLERANCE}")

    def test_no_warnings_from_pixel_math(self, template):
        """Pixel arithmetic must not produce uint8 overflow warnings."""
        art_path = os.path.join(FIXTURES_DIR, "color-block.png")
        art = Image.open(art_path).convert("RGBA")
        result = render_case(art, template, template_dir=TEMPLATE_DIR, fit_mode="cover")
        result_arr = np.array(result)

        # Do some typical pixel math that previously caused overflow
        with warnings.catch_warnings(record=True) as w:
            warnings.simplefilter("always")
            # This should NOT produce RuntimeWarning: overflow
            px = result_arr[500, 500].astype(np.int16)
            base = np.array([248, 247, 245], dtype=np.int16)
            diff = np.abs(px[:3] - base)
            _ = diff.mean()

            overflow_warnings = [
                x for x in w
                if issubclass(x.category, RuntimeWarning)
                and "overflow" in str(x.message).lower()
            ]
            assert len(overflow_warnings) == 0, \
                f"Pixel math produced overflow warnings: {overflow_warnings}"
