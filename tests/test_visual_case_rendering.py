# ─── Print region rounded corner tests (BLOCKER 4) ───────────────────────

class TestPrintRegionCorners:
    """Verify artwork does not leak into the rounded corners of the print region.

    The print mask is the intersection of a rounded print rectangle,
    the case body silhouette, and camera exclusion. At the four
    corners of the print-region bounding box, pixels should fall
    outside the rounded printable area and show base/overlay only —
    not artwork.
    """

    def _corner_point(self, corner_name):
        """Return (x, y) of a point in the rounded-corner annulus.

        The point must be:
          - INSIDE the case body silhouette (on the physical case)
          - OUTSIDE the print region rounded corner (no artwork here)

        Since case body corner and print region corner are concentric
        (radii CORNER_R=150 and PRINT_CORNER_R=130), we pick a point
        in the 20px-wide annulus between them, at ~140px from the
        arc center (45 degree angle from corner).
        """
        # Distance from arc center: halfway between print radius and case radius
        r = (PRINT_CORNER_R + CORNER_R) // 2  # ~140px
        # 45 degree offset from the corner vertex
        offset = int(r * 0.707)  # r * sin(45°) = r / sqrt(2)

        if corner_name == "top-left":
            arc_cx = PRINT_X + PRINT_CORNER_R  # same as case arc cx
            arc_cy = PRINT_Y + PRINT_CORNER_R  # same as case arc cy
            return arc_cx - offset, arc_cy - offset
        elif corner_name == "top-right":
            arc_cx = PRINT_X + PRINT_W - PRINT_CORNER_R
            arc_cy = PRINT_Y + PRINT_CORNER_R
            return arc_cx + offset, arc_cy - offset
        elif corner_name == "bottom-left":
            arc_cx = PRINT_X + PRINT_CORNER_R
            arc_cy = PRINT_Y + PRINT_H - PRINT_CORNER_R
            return arc_cx - offset, arc_cy + offset
        elif corner_name == "bottom-right":
            arc_cx = PRINT_X + PRINT_W - PRINT_CORNER_R
            arc_cy = PRINT_Y + PRINT_H - PRINT_CORNER_R
            return arc_cx + offset, arc_cy + offset
        else:
            raise ValueError(f"Unknown corner: {corner_name}")

    def test_top_left_corner_no_artwork_leak(self, rendered_outputs):
        """Top-left rounded corner of print region should not show artwork color.

        The color-block artwork has red in its top-left quadrant.
        If artwork leaked through the rounded corner, the corner
        pixel would be bright red. With proper masking, it should
        be a neutral case-edge color (not saturated red).
        """
        px, py = self._corner_point("top-left")

        for name, arr in rendered_outputs.items():
            pixel = _pixel(arr, px, py)
            # Pixel should be opaque (on the case body rim/bezel area)
            assert pixel[3] > 50, \
                f"{name}: top-left print corner should be on case body"
            # Pixel should NOT be saturated artwork color
            # For color-block top-left = red: R should not be much higher than G/B
            if name == "color-block":
                r, g, b = pixel[:3]
                # If artwork leaked, R >> G and R >> B
                assert not (r > 150 and r - g > 60), \
                    (f"{name}: top-left corner appears to have red artwork "
                     f"leak (r={r}, g={g}, b={b})")

    def test_top_right_corner_no_artwork_leak(self, rendered_outputs):
        """Top-right rounded corner should not show teal artwork leak.

        Color-block top-right quadrant is teal/green.
        """
        px, py = self._corner_point("top-right")

        for name, arr in rendered_outputs.items():
            pixel = _pixel(arr, px, py)
            assert pixel[3] > 50, \
                f"{name}: top-right print corner should be on case body"
            if name == "color-block":
                r, g, b = pixel[:3]
                # Teal leak would show G >> R
                assert not (g > 150 and g - r > 60), \
                    (f"{name}: top-right corner appears to have teal artwork "
                     f"leak (r={r}, g={g}, b={b})")

    def test_bottom_left_corner_no_artwork_leak(self, rendered_outputs):
        """Bottom-left rounded corner should not show yellow artwork leak.

        Color-block bottom-left quadrant is yellow/gold.
        """
        px, py = self._corner_point("bottom-left")

        for name, arr in rendered_outputs.items():
            pixel = _pixel(arr, px, py)
            assert pixel[3] > 50, \
                f"{name}: bottom-left print corner should be on case body"
            if name == "color-block":
                r, g, b = pixel[:3]
                # Yellow leak would show R and G both high, B low
                assert not (r > 150 and g > 150 and b < 120), \
                    (f"{name}: bottom-left corner appears to have yellow "
                     f"artwork leak (r={r}, g={g}, b={b})")

    def test_bottom_right_corner_no_artwork_leak(self, rendered_outputs):
        """Bottom-right rounded corner should not show blue artwork leak.

        Color-block bottom-right quadrant is navy blue.
        """
        px, py = self._corner_point("bottom-right")

        for name, arr in rendered_outputs.items():
            pixel = _pixel(arr, px, py)
            assert pixel[3] > 50, \
                f"{name}: bottom-right print corner should be on case body"
            if name == "color-block":
                r, g, b = pixel[:3]
                # Navy blue leak would show B >> R
                assert not (b > 100 and b - r > 40), \
                    (f"{name}: bottom-right corner appears to have blue "
                     f"artwork leak (r={r}, g={g}, b={b})")

    def test_center_of_print_region_has_artwork(self, rendered_outputs):
        """Sanity check: print region interior should show artwork.

        Samples at 25% of the print region (well inside the colored
        area, away from the center crosshair of test artworks).
        """
        cx = PRINT_X + int(PRINT_W * 0.25)
        cy = PRINT_Y + int(PRINT_H * 0.25)
        base_color = np.array([248, 247, 245], dtype=np.int16)

        for name, arr in rendered_outputs.items():
            pixel = _pixel(arr, cx, cy)
            assert pixel[3] > 128, \
                f"{name}: print region interior should be opaque"
            diff = _color_distance(pixel, base_color)
            assert diff > 10, \
                (f"{name}: print region interior should show artwork, "
                 f"but looks like bare base (diff={diff:.1f})")


