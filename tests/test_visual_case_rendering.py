# ─── Helper ───────────────────────────────────────────────────────────────

def _pixel(arr, x, y):
    """Return pixel at (x, y) as int16 array to avoid uint8 overflow."""
    return arr[y, x].astype(np.int16)


def _color_distance(p1, p2):
    """Mean absolute channel difference between two int16 pixels."""
    return np.abs(p1[:3] - p2[:3]).mean()


