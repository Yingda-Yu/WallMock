"""
Visual regression tests for the phone case rendering pipeline.

These tests verify structural and visual properties of rendered case
images, using deterministic comparison and reasonable tolerances rather
than fragile byte equality.

The tests load the real iPhone 17e template and render all three fixture
artworks, checking:
  - output dimensions
  - case body presence (non-transparent silhouette)
  - camera module protection
  - print region coverage (including rounded corners)
  - shadow layer correctness (below base, not darkening case body)
  - template reuse without modifications
  - deterministic re-render equality
  - visual regression against saved PNG baselines

Baseline strategy:
  Reference images are small PNG files under tests/fixtures/baselines/.
  They are NOT auto-generated by the test suite — baseline regeneration
  is an explicit developer action via scripts/regenerate_case_baselines.py.
  This prevents CI from silently blessing a changed renderer.
"""

