                pixel = _pixel(arr, sx, sy)
                # No primary color channel should be > 150 (not bright artwork)
                assert pixel[0] < 150 and pixel[1] < 150 and pixel[2] < 150, \
                    f"{name}: lens point ({sx},{sy}) has bright pixel {pixel[:3]}"

